"""Build posed screening sets from LIT-PCBA, under ``examples/litpcba/`` (plan item E4).

Every screening measurement in this repository so far has used a background invented here:
ligands of other targets, or molecules property-matched to the actives out of the sets already
shipped.  Both are *presumed* inactive, and a presumed inactive is an easier case than a
measured one -- a compound that was tested and showed no activity is, by construction, the kind of
molecule a screen actually has to reject.

LIT-PCBA supplies measured ones.  It is assembled from high-confidence PubChem dose-response
assays: 15 targets, 7761 actives and 382674 inactives, all with an experimental result
(Tran-Nguyen, Jacquemard & Rognan, *J. Chem. Inf. Model.* **60** (2020) 4263).  The AVE-unbiased
subsets are used here, which is the form the authors recommend: the asymmetric validation
embedding of Wallach & Heifets removes the analogue bias that otherwise lets a screen score well
by recognising that actives resemble actives.

What this script adds is the thing a field method needs and a SMILES file does not have -- a
conformation and a pose.  For each target:

1. the actives and a seeded sample of the measured inactives are read from the AVE-unbiased
   archive and embedded in 3D with ETKDG and MMFF;
2. the actives are posed by maximising their CMF field similarity to the **crystal ligand** of
   that target, which the archive also ships, so the frame is the one the receptor defines;
3. the inactives are posed by the same criterion, and **against the same crystal ligand**, so
   that both classes are placed by one rule that knows nothing about which of them is active.
   With ``--pose-against actives`` they are instead posed to maximise their similarity to the
   posed actives, which is what :mod:`cmfqsar.decoys` does for the background sets elsewhere in
   this repository.  That is the generous placement -- no inactive is rejected for having been
   posed badly -- and it is generous enough to be worth measuring separately, which
   ``benchmarks/run_screening.py`` does: it adds about +0.19 AUC to the field descriptions
   and exactly nothing to a fingerprint, because optimising each candidate's pose against the
   actives turns the alignment into part of the scoring function.  Note also that the actives
   sampled as the reference (``--ref-max``) are drawn without regard to the train/test split, so
   the generous condition leaks the held-out actives into the inactives' posing.  It is a control,
   not a protocol.

The archive is 57 MB and is not redistributed here; the script downloads it on demand and keeps
it outside the repository.  What is written are the derived structures, in the repository's usual
form: ``<target>.sdf`` with the actives (``subset`` train/test) and ``<target>_decoys.sdf`` with
the posed inactives (``subset = decoy``), which the program loads as a background set.

Usage
-----
    python examples/make_litpcba_examples.py                       # the default targets
    python examples/make_litpcba_examples.py --targets TP53 --inactives 500
    python examples/make_litpcba_examples.py --archive /path/to/AVE_unbiased.tgz
"""
from __future__ import annotations

import argparse
import os
import sys
import tarfile
import time
import urllib.request

import numpy as np
from rdkit import Chem, RDLogger
from rdkit.Chem import AllChem

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))

from cmfqsar.decoys import align_decoys  # noqa: E402
from cmfqsar.fields import AtomTable, FieldSet, build_fields  # noqa: E402

RDLogger.DisableLog("rdApp.*")

URL = "https://drugdesign.unistra.fr/LIT-PCBA/Files/AVE_unbiased.tgz"
OUT = os.path.join(HERE, "litpcba")
#: the two targets whose inactive pools are small enough to pose completely rather than as a
#: small sample: ESR1 antagonists (88 actives, 3820 inactives) and p53 (64, 3345)
TARGETS = ("ESR1_ant", "TP53")
SOURCE = ("LIT-PCBA (AVE-unbiased), Tran-Nguyen, Jacquemard & Rognan, J. Chem. Inf. Model. 60 "
          "(2020) 4263; conformations and poses generated by examples/make_litpcba_examples.py")


def fetch(archive: str) -> str:
    """The archive, downloaded if it is not already where it was asked for."""
    if os.path.isfile(archive):
        return archive
    os.makedirs(os.path.dirname(archive) or ".", exist_ok=True)
    print(f"downloading {URL}\n  to {archive} (57 MB) ...", flush=True)
    urllib.request.urlretrieve(URL, archive)
    return archive


def read_members(archive: str, target: str):
    """(actives, inactives, crystal ligand block) for one target, from the tar directly."""
    actives, inactives, ligand = [], [], None
    with tarfile.open(archive, "r:gz") as tf:
        for m in tf.getmembers():
            parts = m.name.replace("\\", "/").split("/")
            if len(parts) < 2 or parts[0] != target or not m.isfile():
                continue
            leaf = parts[-1]
            if leaf.startswith("active_") and leaf.endswith(".smi"):
                actives += _smi(tf.extractfile(m).read().decode("utf-8", "replace"))
            elif leaf.startswith("inactive_") and leaf.endswith(".smi"):
                inactives += _smi(tf.extractfile(m).read().decode("utf-8", "replace"))
            elif leaf.endswith("_ligand.mol2") and ligand is None:
                ligand = tf.extractfile(m).read().decode("utf-8", "replace")
    return actives, inactives, ligand


def _smi(text: str):
    out = []
    for line in text.splitlines():
        parts = line.split()
        if len(parts) >= 1 and parts[0]:
            out.append((parts[0], parts[1] if len(parts) > 1 else f"m{len(out) + 1}"))
    return out


def embed(smiles: str, name: str, seed: int):
    """One molecule in 3D, or None when RDKit cannot make one."""
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return None
    mol = Chem.AddHs(mol)
    p = AllChem.ETKDGv3()
    p.randomSeed = int(seed)
    if AllChem.EmbedMolecule(mol, p) != 0:
        p.useRandomCoords = True
        if AllChem.EmbedMolecule(mol, p) != 0:
            return None
    try:
        AllChem.MMFFOptimizeMolecule(mol, maxIters=400)
    except Exception:                        # noqa: BLE001 - a molecule MMFF cannot type
        pass
    mol.SetProp("_Name", name)
    return mol


def build(target: str, archive: str, n_inactives: int, alpha: float, restarts: int,
          ref_max: int, seed: int, out_dir: str = OUT, pose_against: str = "crystal") -> None:
    t0 = time.time()
    actives, inactives, ligand_block = read_members(archive, target)
    if not actives:
        print(f"{target}: not in the archive, skipped")
        return
    rng = np.random.RandomState(seed)
    if n_inactives and len(inactives) > n_inactives:
        pick = rng.choice(len(inactives), size=n_inactives, replace=False)
        inactives = [inactives[int(i)] for i in sorted(pick)]
    print(f"=== {target}: {len(actives)} actives, {len(inactives)} measured inactives "
          f"(of the pool), seed {seed}", flush=True)

    fs = FieldSet.create(alpha=alpha)
    reference = None
    if ligand_block is not None:
        ref_mol = Chem.MolFromMol2Block(ligand_block, removeHs=False, sanitize=True)
        if ref_mol is None:
            ref_mol = Chem.MolFromMol2Block(ligand_block, removeHs=False, sanitize=False)
        if ref_mol is not None and ref_mol.GetNumConformers():
            reference = AtomTable.from_molecules([build_fields(ref_mol, fs, "crystal")])
            print(f"    the crystal ligand gives the frame: {ref_mol.GetNumAtoms()} atoms",
                  flush=True)
    if reference is None:
        raise SystemExit(f"{target}: no crystal ligand to define a frame")

    act_mols, act_names = [], []
    for i, (smi, name) in enumerate(actives):
        m = embed(smi, f"{target}_active_{name}", seed + i)
        if m is not None:
            act_mols.append(m)
            act_names.append(m.GetProp("_Name"))
    print(f"    {len(act_mols)}/{len(actives)} actives embedded "
          f"({time.time() - t0:.0f} s)", flush=True)

    af = [build_fields(m, fs, n) for m, n in zip(act_mols, act_names)]
    align_decoys(af, reference, fs, restarts=restarts, seed=seed,
                 progress=lambda i, n: print(f"      actives posed {i}/{n}", flush=True)
                 if i % 25 == 0 or i == n else None)
    for m, f in zip(act_mols, af):
        conf = m.GetConformer()
        for a, xyz in enumerate(f.coords):
            conf.SetAtomPosition(a, [float(v) for v in xyz])

    # what the inactives are posed against: the crystal ligand, the same reference the actives
    # were given, or the actives themselves when the generous placement is asked for
    if pose_against == "actives":
        idx = list(range(len(af)))
        if ref_max and len(idx) > ref_max:
            step = len(idx) / float(ref_max)
            idx = [idx[int(k * step)] for k in range(ref_max)]
        act_ref = AtomTable.from_molecules([af[i] for i in idx])
        print(f"    the inactives are posed against {len(idx)} posed actives (the generous "
              f"placement)", flush=True)
    else:
        act_ref = reference
        print("    the inactives are posed against the crystal ligand, as the actives were",
              flush=True)

    dec_mols, dec_fields = [], []
    for i, (smi, name) in enumerate(inactives):
        m = embed(smi, f"{target}_inactive_{name}", seed + 100000 + i)
        if m is None:
            continue
        dec_mols.append(m)
        dec_fields.append(build_fields(m, fs, m.GetProp("_Name")))
        if (i + 1) % 250 == 0:
            print(f"      {i + 1}/{len(inactives)} inactives embedded "
                  f"({time.time() - t0:.0f} s)", flush=True)
    align_decoys(dec_fields, act_ref, fs, restarts=restarts, seed=seed,
                 progress=lambda i, n: print(f"      inactives posed {i}/{n} "
                                             f"({time.time() - t0:.0f} s)", flush=True)
                 if i % 100 == 0 or i == n else None)
    for m, f in zip(dec_mols, dec_fields):
        conf = m.GetConformer()
        for a, xyz in enumerate(f.coords):
            conf.SetAtomPosition(a, [float(v) for v in xyz])

    os.makedirs(out_dir, exist_ok=True)
    # the actives carry an activity of 1 and a split; the inactives are the background
    half = rng.permutation(len(dec_mols))
    a_path = os.path.join(out_dir, f"{target}.sdf")
    with Chem.SDWriter(a_path) as w:
        order = rng.permutation(len(act_mols))
        for k, j in enumerate(order):
            m = Chem.Mol(act_mols[int(j)])
            m.SetProp("activity", "1")
            m.SetProp("subset", "train" if k < int(0.7 * len(order)) else "test")
            m.SetProp("source", SOURCE)
            w.write(m)
    tag = "_decoys" if pose_against == "crystal" else "_decoys_similar"
    d_path = os.path.join(out_dir, f"{target}{tag}.sdf")
    with Chem.SDWriter(d_path) as w:
        for j in half:
            m = Chem.Mol(dec_mols[int(j)])
            m.SetProp("activity", "0")
            m.SetProp("subset", "decoy")
            m.SetProp("source", SOURCE)
            w.write(m)
    print(f"    written {a_path} ({len(act_mols)}) and {d_path} ({len(dec_mols)})  "
          f"[{time.time() - t0:.0f} s]", flush=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--targets", nargs="*", default=list(TARGETS))
    ap.add_argument("--inactives", type=int, default=1500,
                    help="how many measured inactives to keep per target (0 = all)")
    ap.add_argument("--alpha", type=float, default=0.5)
    ap.add_argument("--restarts", type=int, default=4, help="restarts of the posing search")
    ap.add_argument("--ref-max", type=int, default=40,
                    help="actives used as the frame the inactives are posed against")
    ap.add_argument("--pose-against", default="crystal", choices=["crystal", "actives"],
                    help="what the inactives are posed against: the crystal ligand, which is "
                         "the same rule the actives were posed by and knows nothing about them, "
                         "or the actives themselves, which is the generous placement")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--archive", default=os.path.join(OUT, "AVE_unbiased.tgz"),
                    help="where the LIT-PCBA archive is, or should be downloaded to")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()
    archive = fetch(a.archive)
    for target in a.targets:
        build(target, archive, a.inactives, a.alpha, a.restarts, a.ref_max, a.seed, a.out,
              pose_against=a.pose_against)


if __name__ == "__main__":
    main()
